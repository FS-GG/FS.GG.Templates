#!/usr/bin/env bash
# Cold public-only source compiler stage. The external admitted controller owns
# executable/native closure, capacity, original clock, logs and process retirement.
# This script is not a product qualification or publication authority.
set -euo pipefail
umask 077
: "${FSGG_SOURCE_STAGE_ROOT:?absent private source-stage root required}"
: "${FSGG_QUALIFIED_SDK_ROOT:?independently qualified SDK401 role required}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P)"
case "$FSGG_SOURCE_STAGE_ROOT" in /*) ;; *) exit 3;; esac
[[ ! -e "$FSGG_SOURCE_STAGE_ROOT" && ! -L "$FSGG_SOURCE_STAGE_ROOT" ]] || { echo 'existing source stage refused' >&2; exit 3; }
[[ -f "$FSGG_QUALIFIED_SDK_ROOT/dotnet" && ! -L "$FSGG_QUALIFIED_SDK_ROOT/dotnet" ]] || exit 3
STAGE="$FSGG_SOURCE_STAGE_ROOT"
mkdir "$STAGE"
mkdir "$STAGE/source" "$STAGE/output" "$STAGE/receipts" "$STAGE/dotnet-home" "$STAGE/packages" "$STAGE/http" "$STAGE/tmp"
for name in FS.GG.Templates.PolyglotProviderTool.fsproj Catalog.fs Provenance.fs Fixture.fs Program.fs; do
  original="$ROOT/tools/FS.GG.Templates.PolyglotProviderTool/$name"
  [[ -f "$original" && ! -L "$original" ]] || exit 3
  cp -- "$original" "$STAGE/source/$name"
  cmp -- "$original" "$STAGE/source/$name"
done
(cd "$STAGE/source" && sha256sum -- *.fs *.fsproj) > "$STAGE/receipts/source-before.sha256"
cat > "$STAGE/NuGet.Config" <<'CONFIG'
<?xml version="1.0" encoding="utf-8"?>
<configuration><packageSources><clear/><add key="public" value="https://api.nuget.org/v3/index.json"/></packageSources><disabledPackageSources><clear/></disabledPackageSources></configuration>
CONFIG
printf '{"sdk":{"version":"10.0.401","rollForward":"disable","allowPrerelease":false}}\n' > "$STAGE/global.json"
# Preserve actual HOME/CODEX_HOME. All mutable SDK roles are operation-private.
export DOTNET_ROOT="$FSGG_QUALIFIED_SDK_ROOT" DOTNET_CLI_HOME="$STAGE/dotnet-home"
export NUGET_PACKAGES="$STAGE/packages" NUGET_HTTP_CACHE_PATH="$STAGE/http" TMPDIR="$STAGE/tmp"
export DOTNET_MULTILEVEL_LOOKUP=0 DOTNET_NOLOGO=1 DOTNET_CLI_TELEMETRY_OPTOUT=1
export DOTNET_SKIP_FIRST_TIME_EXPERIENCE=1 MSBUILDDISABLENODEREUSE=1 DOTNET_CLI_USE_MSBUILD_SERVER=0
unset MSBuildSDKsPath MSBuildExtensionsPath MSBUILD_EXE_PATH
cd "$STAGE/source"
dotnet="$DOTNET_ROOT/dotnet"
common=(-p:ImportDirectoryBuildProps=false -p:ImportDirectoryBuildTargets=false -p:ImportDirectoryPackagesProps=false -p:ManagePackageVersionsCentrally=false)
"$dotnet" restore FS.GG.Templates.PolyglotProviderTool.fsproj --configfile "$STAGE/NuGet.Config" --packages "$STAGE/packages" --no-cache --force-evaluate "${common[@]}" -p:NuGetAudit=false --verbosity minimal
# Verify actual restore resolution before compiler/package targets can run.
python3 -I -B "$ROOT/scripts/polyglot/check-cold-assets.py" "$STAGE"
"$dotnet" build FS.GG.Templates.PolyglotProviderTool.fsproj --no-restore --configuration Release --output "$STAGE/output" --disable-build-servers -m:1 "${common[@]}" -p:UseSharedCompilation=false -p:ContinuousIntegrationBuild=true --verbosity minimal
(cd "$STAGE/source" && sha256sum --check --strict "$STAGE/receipts/source-before.sha256")
for name in FS.GG.Templates.PolyglotProviderTool.fsproj Catalog.fs Provenance.fs Fixture.fs Program.fs; do
  cmp -- "$ROOT/tools/FS.GG.Templates.PolyglotProviderTool/$name" "$STAGE/source/$name"
done
(cd "$STAGE/output" && find . -type f -print0 | sort -z | xargs -0 sha256sum) > "$STAGE/receipts/owned-output.sha256"
assembly="$STAGE/output/FS.GG.Templates.PolyglotProviderTool.dll"
[[ -f "$assembly" && ! -L "$assembly" ]] || exit 3
"$dotnet" exec --fx-version 10.0.12 "$assembly" self-test
"$dotnet" exec --fx-version 10.0.12 "$assembly" emit --package-version 0.20.0 --output "$STAGE/catalog-first.json"
"$dotnet" exec --fx-version 10.0.12 "$assembly" emit --package-version 0.20.0 --output "$STAGE/catalog-second.json"
cmp -- "$STAGE/catalog-first.json" "$STAGE/catalog-second.json"
"$dotnet" exec --fx-version 10.0.12 "$assembly" check --package-version 0.20.0 --output "$STAGE/catalog-first.json"
(cd "$STAGE/output" && sha256sum --check --strict "$STAGE/receipts/owned-output.sha256")
# Do not copy generated bytes into the source checkout or pack/publish here.
