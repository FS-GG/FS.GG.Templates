import { chromium, firefox, webkit } from "@playwright/test";

const family=process.argv[2];
const address=process.argv[3];
const kind={chromium,firefox,webkit}[family];
if(!kind||!address) throw new Error("usage: node svg-input-observe.mjs <chromium|firefox|webkit> <address>");
const external=family==="chromium"?process.env.PLAYWRIGHT_EXECUTABLE_PATH:family==="firefox"?process.env.PLAYWRIGHT_FIREFOX_EXECUTABLE_PATH:process.env.PLAYWRIGHT_WEBKIT_EXECUTABLE_PATH;
const browser=await kind.launch({headless:true,executablePath:external||undefined});
try {
  const page=await browser.newPage();
  await page.addInitScript(()=>{
    globalThis.__svgInputPads=[];
    Object.defineProperty(navigator,"getGamepads",{configurable:true,value:()=>globalThis.__svgInputPads});
  });
  await page.goto(address,{waitUntil:"networkidle"});
  await page.waitForFunction(()=>window.svgGeneratedStudio);
  const click=async name=>page.getByRole("button",{name,exact:true}).click();
  const scene=page.locator("#generated-authoring-studio--scene");
  const expectSceneFocus=async context=>{
    await page.waitForFunction(()=>document.activeElement?.id==="generated-authoring-studio--scene");
    if(!(await scene.evaluate(element=>element===document.activeElement))) throw new Error(`${context} did not restore scene focus`);
  };

  await scene.focus();
  await page.keyboard.press("1");
  await page.keyboard.press("2");
  await page.waitForFunction(()=>document.querySelector("#svg-authoring-studio")?.getAttribute("data-workspace-mode")==="arrange");
  await page.keyboard.press("3");
  await page.waitForFunction(()=>document.querySelector("#svg-authoring-studio")?.getAttribute("data-workspace-mode")==="play");
  await page.keyboard.press("4");
  await page.waitForFunction(()=>document.querySelector("#svg-authoring-studio")?.getAttribute("data-workspace-mode")==="review");
  await click("Collapse side docks");
  const collapsed=await page.evaluate(()=>window.svgGeneratedStudio.snapshot().collapsedPanelCount);
  await click("Restore side docks");
  const restored=await page.evaluate(()=>window.svgGeneratedStudio.snapshot().collapsedPanelCount);
  if(collapsed<1||restored!==0) throw new Error(JSON.stringify({collapsed,restored}));
  await scene.focus();
  await page.keyboard.press("Control+k");
  await page.getByRole("dialog",{name:"Command palette"}).waitFor();
  await page.keyboard.press("Escape");
  await expectSceneFocus("Ctrl+K palette");
  await scene.dispatchEvent("keydown",{key:"k",code:"KeyK",metaKey:true,bubbles:true});
  await scene.dispatchEvent("keyup",{key:"k",code:"KeyK",metaKey:true,bubbles:true});
  await page.getByRole("dialog",{name:"Command palette"}).waitFor();
  await page.keyboard.press("Escape");
  await expectSceneFocus("Meta+K palette");
  await page.keyboard.press("g");
  await page.keyboard.press("h");
  await page.getByRole("dialog",{name:"Possible input help"}).waitFor();
  await page.keyboard.press("Escape");
  await expectSceneFocus("input help");
  await page.keyboard.press("r");
  await page.getByRole("dialog",{name:"Rebind command"}).waitFor();
  await page.keyboard.press("1");
  await page.waitForFunction(()=>document.querySelector("[data-fsgg-workspace-overlay='rebind']")?.hasAttribute("hidden")===true);
  await page.waitForFunction(()=>document.querySelector("#generated-scene-status")?.textContent?.includes("displaced commands: 1"));
  if(await page.evaluate(()=>document.activeElement?.id)!=="generated-authoring-studio--scene") throw new Error("rebind did not restore scene focus");
  await scene.focus();
  await page.keyboard.press("1");
  await page.getByRole("dialog",{name:"Command palette"}).waitFor();
  await page.keyboard.press("Escape");
  await expectSceneFocus("rebound palette");
  await scene.dispatchEvent("pointerdown",{pointerId:31,pointerType:"mouse",bubbles:true});
  await scene.dispatchEvent("pointerup",{pointerId:31,pointerType:"mouse",bubbles:true});
  await scene.dispatchEvent("pointerdown",{pointerId:32,pointerType:"touch",bubbles:true});
  await scene.dispatchEvent("pointerup",{pointerId:32,pointerType:"touch",bubbles:true});
  await page.evaluate(()=>{
    globalThis.__svgInputPads=[{index:0,connected:true,buttons:[{pressed:true}]}];
    window.svgGeneratedStudio.pollGamepads();
    globalThis.__svgInputPads=[{index:0,connected:true,buttons:[{pressed:false}]}];
    window.svgGeneratedStudio.pollGamepads();
  });
  await click("Gamepad workspace action");
  const input=await page.evaluate(()=>window.svgGeneratedStudio.snapshot());
  if(input.workspaceMode!=="play"||input.inputBindingCount!==9||input.inputLifecycle.IsDisposed) throw new Error(JSON.stringify({input}));
  await click("Rectangle");
  await click("Path");
  await click("Save asset");
  await click("Place two instances");
  await click("Edit scene properties");
  await click("Author grid and freeform");
  await click("Create asset revision");
  const conflicted=await page.evaluate(()=>window.svgGeneratedStudio.snapshot());
  await click("Resolve asset conflicts");
  await click("Undo scene change");
  const undone=await page.evaluate(()=>window.svgGeneratedStudio.snapshot());
  await click("Redo scene change");
  const combinedSave=page.getByRole("button",{name:"Save and reload scene",exact:true});
  if(await combinedSave.count()) {
    await combinedSave.click();
  } else {
    const beforePersist=await page.evaluate(()=>window.svgGeneratedStudio.snapshot());
    await click("Save scene in browser");
    await page.waitForFunction(()=>document.querySelector("[role=status]")?.textContent?.includes("persisted in browser storage"));
    await page.reload({waitUntil:"networkidle"});
    await page.waitForFunction(()=>window.svgGeneratedStudio);
    await page.waitForFunction(()=>document.querySelector("[role=status]")?.textContent?.includes("Persisted scene loaded"));
    const afterPersist=await page.evaluate(()=>window.svgGeneratedStudio.snapshot());
    for(const field of ["documentId","contentHash","assets","instances"])
      if(afterPersist[field]!==beforePersist[field]) throw new Error(JSON.stringify({field,beforePersist,afterPersist}));
  }
  await click("Verify Noto text");
  await page.waitForFunction(()=>document.querySelector("[role=status]")?.textContent?.includes("reopened offline"));
  await click("Run Boolean union");
  await page.waitForFunction(()=>document.querySelector("[role=status]")?.textContent?.includes("committed once"));
  await click("Grid snapping");
  await click("Object");
  await click("Freeform");
  await click("Boundary");
  await click("Migrate legacy content");
  const final=await page.evaluate(()=>window.svgGeneratedStudio.snapshot());
  const descriptorValid=await page.evaluate(()=>window.svgGeneratedStudio.descriptorsValid());
  const rendered=await page.locator("[data-fsgg-document-id]").locator("path,rect,ellipse").count();
  if(conflicted.conflicts!==1||undone.conflicts!==1||final.conflicts!==0||final.assets!==2||final.instances!==2||final.entities!==5||final.schema!=="fsgg.svg-scene/1"||!descriptorValid||rendered<3) throw new Error(JSON.stringify({conflicted,undone,final,descriptorValid,rendered}));
  const beforeDispose=await page.evaluate(()=>window.svgGeneratedStudio.snapshot().inputLifecycle);
  await page.evaluate(()=>window.svgGeneratedStudio.disposeInput());
  const afterDispose=await page.evaluate(()=>window.svgGeneratedStudio.snapshot().inputLifecycle);
  if(beforeDispose.OwnedListenerCount<1||!beforeDispose.GamepadPollScheduled||afterDispose.OwnedListenerCount!==0||afterDispose.OwnedDeadlineCount!==0||afterDispose.OwnedSourceCount!==0||afterDispose.GamepadPollScheduled||!afterDispose.IsDisposed) throw new Error(JSON.stringify({beforeDispose,afterDispose}));
  console.log(JSON.stringify({family,result:"passed",input,conflicted,undone,final,descriptorValid,rendered,beforeDispose,afterDispose}));
} finally { await browser.close(); }
